const { chromium } = require('playwright'); const path = require('path');
const dist = path.resolve(process.argv[2] || 'dist-live');
(async () => {
  const browser = await chromium.launch(); const page = await browser.newPage({ viewport: { width: 1366, height: 900 } });
  let posted = null; let mode = 'ok';
  await page.route('https://formspree.io/**', async route => { posted = JSON.parse(route.request().postData()); await route.fulfill({ status: mode === 'ok' ? 200 : 500, contentType: 'application/json', body: '{"ok":true}' }); });
  await page.goto('file://' + path.join(dist, 'contact.html')); await page.waitForTimeout(500);
  console.log('demo-notice aanwezig?', await page.locator('text=nog niet aangesloten').count(), '| knop:', await page.locator('button[type=submit]').textContent());
  await page.click('label.l-choice:has-text("Ik ben werkgever")');
  await page.fill('#veld-naam', 'Test Persoon'); await page.fill('#veld-email', 'test@voorbeeld.nl'); await page.fill('#veld-tekst', 'Graag een kennismaking.');
  await page.click('button[type=submit]'); await page.waitForTimeout(600);
  console.log('verzonden ->', (await page.locator('[role=status] h2').textContent()), '| payload:', JSON.stringify(posted));
  await page.click('text=Nog een bericht sturen'); await page.waitForTimeout(300);
  mode = 'fail';
  await page.click('label.l-choice:has-text("gemeente")'); await page.fill('#veld-naam', 'Fout Test'); await page.fill('#veld-tel', '0612345678');
  await page.click('button[type=submit]'); await page.waitForTimeout(600);
  console.log('fout ->', (await page.locator('[role=alert]').first().textContent()).slice(0, 60));
  console.log('footer e-mail link:', await page.locator('footer a[href^="mailto:"]').count(), '| sitemap:', require('fs').existsSync(path.join(dist, 'sitemap.xml')));
  await browser.close();
})().catch(e => { console.error('TESTFOUT', e.message); process.exit(1); });
